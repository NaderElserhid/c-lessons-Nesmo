#include <iostream>
#include <vector>
#include <algorithm>

using namespace std;

// نستخدم قيمة سالبة صغيرة جداً كقيمة ابتدائية للبحث عن "الحد الأقصى"
// لأن قيم الشبكة قد تكون سالبة، فلا يمكننا استخدام الصفر كقيمة ابتدائية.
const long long INF = 2e18;

int main() {
    // هذه الأسطر تُستخدم لتسريع عمليات الإدخال والإخراج في C++
    // لتجنب مشكلة تجاوز الوقت (Time Limit Exceeded) في المسائل التنافسية.
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);

    int N, K;
    // قراءة حجم الشبكة (N) وحجم المربع المطلوب (K)
    if (!(cin >> N >> K)) return 0;

    // تعريف مصفوفة ثنائية الأبعاد للشبكة الأصلية بحجم (N+1) x (N+1)
    // أضفنا 1 لنجعل الفهارس (Index) تبدأ من 1 بدلاً من 0 لتسهيل حسابات المصفوفة التراكمية.
    vector<vector<long long>> grid(N + 1, vector<long long>(N + 1, 0));

    // تعريف المصفوفة التراكمية (2D Prefix Sum) بنفس الحجم.
    // هذه المصفوفة ستخزن مجموع العناصر من النقطة (1,1) وحتى النقطة (i,j).
    vector<vector<long long>> pref(N + 1, vector<long long>(N + 1, 0));

    // الحلقة التكرارية الأولى: قراءة البيانات وبناء المصفوفة التراكمية في نفس الوقت.
    for (int i = 1; i <= N; ++i) {
        for (int j = 1; j <= N; ++j) {
            cin >> grid[i][j];
            // معادلة المصفوفة التراكمية ثنائية الأبعاد (Inclusion-Exclusion Principle):
            // المجموع التراكمي للنقطة الحالية =
            // قيمتها + المجموع التراكمي للمربع أعلاها + المجموع التراكمي للمربع يسارها - التقاطع بينهما (حتى لا يُحسب مرتين)
            pref[i][j] = grid[i][j] + pref[i-1][j] + pref[i][j-1] - pref[i-1][j-1];
        }
    }

    // تعريف دالة مساعدة (Lambda Function) لحساب مجموع أي مستطيل داخل الشبكة بسرعة فائقة O(1).
    // تعتمد الدالة على المصفوفة التراكمية التي بنيناها للتو.
    auto get_sum = [&](int r1, int c1, int r2, int c2) {
        // المجموع = المربع الكبير الكلي - المستطيل العلوي (خارج النطاق) - المستطيل الأيسر (خارج النطاق) + التقاطع (الذي طُرح مرتين)
        return pref[r2][c2] - pref[r1-1][c2] - pref[r2][c1-1] + pref[r1-1][c1-1];
    };

    // مصفوفة 'val' لتخزين مجموع كل مربع KxK ممكن داخل الشبكة.
    // الإحداثيات (i, j) تمثل الزاوية اليسرى العليا للمربع.
    vector<vector<long long>> val(N + 1, vector<long long>(N + 1, -INF));

    // نمر على كل نقطة يمكن أن تكون بداية (زاوية يسرى عليا) لمربع KxK.
    for (int i = 1; i <= N - K + 1; ++i) {
        for (int j = 1; j <= N - K + 1; ++j) {
            // نستخدم الدالة المساعدة لحساب مجموع المربع الذي يبدأ في (i, j) وينتهي في (i+K-1, j+K-1)
            val[i][j] = get_sum(i, j, i + K - 1, j + K - 1);
        }
    }

    // هنا تكمن قوة البرمجة الديناميكية:
    // مصفوفات لتخزين "أكبر مربع KxK" وجدناه حتى الآن عند المسح من الاتجاهات الأربعة.
    vector<long long> max_up(N + 2, -INF);    // من الصف الأعلى نزولاً للأسفل
    vector<long long> max_down(N + 2, -INF);  // من الصف الأسفل صعوداً للأعلى
    vector<long long> max_left(N + 2, -INF);  // من العمود الأيسر مروراً لليمين
    vector<long long> max_right(N + 2, -INF); // من العمود الأيمن مروراً لليسار

    // 1. حساب max_up: أكبر مربع KxK موجود بالكامل في الصفوف من 1 إلى i
    for (int i = K; i <= N; ++i) {
        long long mx = -INF;
        int r = i - K + 1; // صف البداية للمربعات التي تنتهي عند الصف i
        // نبحث عن أكبر مربع KxK في هذا الصف الأفقي المحدد
        for (int c = 1; c <= N - K + 1; ++c) mx = max(mx, val[r][c]);
        // القيمة العظمى هي إما المربع الأكبر في هذا الصف، أو القيمة العظمى من الصفوف التي فوقه
        max_up[i] = max(max_up[i-1], mx);
    }

    // 2. حساب max_down: أكبر مربع KxK موجود بالكامل في الصفوف من i إلى N
    for (int i = N - K + 1; i >= 1; --i) {
        long long mx = -INF;
        int r = i; // صف البداية
        // نبحث عن أكبر مربع في هذا الصف
        for (int c = 1; c <= N - K + 1; ++c) mx = max(mx, val[r][c]);
        // القيمة العظمى هي الأكبر في هذا الصف أو الصفوف التي تحته
        max_down[i] = max(max_down[i+1], mx);
    }

    // 3. حساب max_left: أكبر مربع KxK موجود بالكامل في الأعمدة من 1 إلى j
    for (int j = K; j <= N; ++j) {
        long long mx = -INF;
        int c = j - K + 1; // عمود البداية للمربعات التي تنتهي عند العمود j
        for (int r = 1; r <= N - K + 1; ++r) mx = max(mx, val[r][c]);
        max_left[j] = max(max_left[j-1], mx);
    }

    // 4. حساب max_right: أكبر مربع KxK موجود بالكامل في الأعمدة من j إلى N
    for (int j = N - K + 1; j >= 1; --j) {
        long long mx = -INF;
        int c = j;
        for (int r = 1; r <= N - K + 1; ++r) mx = max(mx, val[r][c]);
        max_right[j] = max(max_right[j+1], mx);
    }

    // المتغير الذي سيحفظ الحل النهائي (أكبر مجموع لمربعين غير متقاطعين)
    long long ans = -INF;

    // الخطوة الأخيرة: تجربة جميع "خطوط الفصل" الممكنة بين المربعين.
    // بما أن المربعين غير متقاطعين، فإما أن يكون بينهما خط فصل أفقي أو عمودي.

    // الاحتمال الأول: يوجد خط فصل أفقي يقطع الشبكة بين الصف i والصف i+1
    for (int i = K; i <= N - K; ++i) {
        // إذا كان هناك مربع صالح في الجزء العلوي ومربع صالح في الجزء السفلي
        if (max_up[i] != -INF && max_down[i+1] != -INF)
            // نحدث الإجابة إذا كان مجموعهما أكبر من الإجابة الحالية
            ans = max(ans, max_up[i] + max_down[i+1]);
    }

    // الاحتمال الثاني: يوجد خط فصل عمودي يقطع الشبكة بين العمود j والعمود j+1
    for (int j = K; j <= N - K; ++j) {
        // إذا كان هناك مربع صالح في الجزء الأيسر ومربع صالح في الجزء الأيمن
        if (max_left[j] != -INF && max_right[j+1] != -INF)
            // نحدث الإجابة إذا كان مجموعهما أكبر
            ans = max(ans, max_left[j] + max_right[j+1]);
    }

    // طباعة النتيجة النهائية
    cout << ans << "\n";
    return 0;
}
